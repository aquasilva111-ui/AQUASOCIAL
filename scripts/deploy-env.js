const {Buffer} = require('node:buffer')
const fs = require('node:fs')
const path = require('node:path')

/**
 * Production is only the public site. Every other host — teste.aquaapp.systems,
 * a Cloudflare Pages preview, a Hostinger preview hostname — is non-production.
 * AQUA_DEPLOY_ENV selects the static files baked into the build. When it is
 * absent, the build stays indexable so the current Hostinger production
 * deploy keeps working without new environment variables. Cloudflare Pages
 * sets CF_PAGES=1; that default is preview, because Pages is never the
 * public host. An explicit AQUA_DEPLOY_ENV still wins.
 */
const DEPLOY_ENVS = ['production', 'staging', 'preview']
const PRODUCTION_HOSTS = new Set(['aquaapp.systems', 'www.aquaapp.systems'])
const ROBOTS_META = '<meta name="robots" content="noindex, nofollow">'
const ROBOTS_HEADER_VALUE = 'noindex, nofollow'
const DISALLOW_ROBOTS = 'User-agent: *\nDisallow: /\n'

function resolveDeployEnv(env = process.env) {
  const raw = String(env.AQUA_DEPLOY_ENV ?? '')
    .trim()
    .toLowerCase()
  if (!raw) {
    if (String(env.CF_PAGES ?? '') === '1') return 'preview'
    return 'production'
  }
  if (!DEPLOY_ENVS.includes(raw)) {
    throw new Error(
      `AQUA_DEPLOY_ENV must be production, staging, or preview (got ${JSON.stringify(raw)})`,
    )
  }
  return raw
}

function isProductionDeployEnv(env = process.env) {
  return resolveDeployEnv(env) === 'production'
}

function hostnameFromHostHeader(host) {
  const source = Array.isArray(host) ? host[0] : host
  let value = String(source ?? '')
    .trim()
    .toLowerCase()
  if (!value) return ''
  if (value.startsWith('[')) {
    const end = value.indexOf(']')
    value = end === -1 ? '' : value.slice(1, end)
  } else {
    const colon = value.lastIndexOf(':')
    if (
      colon !== -1 &&
      value.indexOf(':') === colon &&
      /^\d+$/.test(value.slice(colon + 1))
    ) {
      value = value.slice(0, colon)
    }
  }
  if (value.endsWith('.')) value = value.slice(0, -1)
  return value
}

function isProductionHost(host) {
  return PRODUCTION_HOSTS.has(hostnameFromHostHeader(host))
}

/**
 * Build-time indexability. Pass `host` only when the request host is known.
 * A known non-production host is never indexable. An unknown host follows
 * the build variable, which defaults to production.
 */
function isIndexableDeployment({deployEnv, host, env = process.env} = {}) {
  const mode = deployEnv ?? resolveDeployEnv(env)
  if (mode !== 'production') return false
  if (host == null) return true
  return isProductionHost(host)
}

function ensureRobotsMeta(html) {
  if (/<meta\b[^>]*\bname\s*=\s*["']robots["']/i.test(html)) return html
  if (/<head\b[^>]*>/i.test(html)) {
    return html.replace(
      /<head\b[^>]*>/i,
      match => `${match}\n    ${ROBOTS_META}`,
    )
  }
  if (/<html\b[^>]*>/i.test(html)) {
    return html.replace(/<html\b[^>]*>/i, match => `${match}${ROBOTS_META}`)
  }
  return html
}

function applyPublicRobots(projectRoot, outDir, env = process.env) {
  const mode = resolveDeployEnv(env)
  const production = fs.readFileSync(
    path.join(projectRoot, 'web', 'robots.txt'),
  )
  const disallow = Buffer.from(DISALLOW_ROBOTS)
  const hidden = path.join(outDir, '_aqua-pages')
  fs.mkdirSync(hidden, {recursive: true})
  // Hostname routing serves these. They are not public URLs: _aqua-pages is
  // blocked by .htaccess and server.js. robots.txt itself is the static copy
  // a host without rewrite rules will serve (Cloudflare Pages).
  fs.writeFileSync(path.join(hidden, 'robots.production.txt'), production)
  fs.writeFileSync(path.join(hidden, 'robots.disallow.txt'), disallow)
  fs.writeFileSync(
    path.join(outDir, 'robots.txt'),
    mode === 'production' ? production : disallow,
  )
  return mode
}

function cloudflareHeaders() {
  return (
    '# Cloudflare Pages is a preview host. It does not serve aquaapp.systems.\n' +
    '# Hostinger Apache ignores this file and uses .htaccess.\n' +
    '/*\n' +
    '  X-Robots-Tag: noindex, nofollow\n'
  )
}

function cloudflareRedirects(pathnames) {
  const lines = [
    '# Generated by scripts/build-site-discovery.js.',
    '# A file that exists in this build (robots.txt, sitemap, /static) is served as-is.',
    '# Every other path uses the app shell so a Pages preview can open client routes.',
  ]
  for (const pathname of [...new Set(pathnames)]) {
    if (pathname === '/') continue
    const target = `/_aqua-pages${pathname}.html`
    lines.push(`${pathname} ${target} 200`)
    lines.push(`${pathname}/ ${target} 200`)
  }
  lines.push('/videos /views 301')
  lines.push('/videos/ /views 301')
  lines.push('/videos/* /views/:splat 301')
  lines.push('/* /_aqua-pages/app.html 200')
  return `${lines.join('\n')}\n`
}

function writeCloudflarePagesFiles(outDir, pathnames) {
  fs.mkdirSync(outDir, {recursive: true})
  fs.writeFileSync(path.join(outDir, '_headers'), cloudflareHeaders())
  fs.writeFileSync(
    path.join(outDir, '_redirects'),
    cloudflareRedirects(pathnames),
  )
}

module.exports = {
  DEPLOY_ENVS,
  PRODUCTION_HOSTS,
  ROBOTS_META,
  ROBOTS_HEADER_VALUE,
  DISALLOW_ROBOTS,
  resolveDeployEnv,
  isProductionDeployEnv,
  hostnameFromHostHeader,
  isProductionHost,
  isIndexableDeployment,
  ensureRobotsMeta,
  applyPublicRobots,
  cloudflareHeaders,
  cloudflareRedirects,
  writeCloudflarePagesFiles,
}
